/**
 * 共通テスト用プログラム表記（新DNCL）への対応を検査するテスト
 *
 *   node dncl/test_notation.js
 *
 * 【このテストの位置づけ】
 * 2026-07-30 の評価で、インタプリタの表記が **旧DNCL（情報関係基礎）寄り**で、
 * 現行の共通テスト「情報Ⅰ」の表記と食い違っていることが判明した。
 * ここに書いてある NG を OK に変えるのが作業のゴール。
 * **既存の書き方（「〜 を表示する」「かつ」など）も通り続けること**が条件（両対応にする）。
 *
 * 公式表記の出典: https://note.com/toppakou/n/n08dfe37acc78
 *   代入 =／比較 == != > >= <= <／乗算 *／除算 /／整数除算 ÷／剰余 %
 *   出力 表示する(値, 値)／論理 and or not／2次元配列 A[i,j]／else if は「そうでなくもし」
 */
const DNCLInterpreter = require("./dncl-interpreter.js");

const B = (text, indent = 0) => ({ text, indent });
let pass = 0;
let fail = 0;

function check(name, blocks, initialVars, expected) {
  const r = new DNCLInterpreter().run(blocks, initialVars || {});
  const out = (r.output || []).join(",");
  const ok = r.success && out === expected;
  if (ok) {
    pass++;
    console.log(`OK   ${name}`);
  } else {
    fail++;
    console.log(`NG   ${name}`);
    console.log(`       出力=[${out}] 期待=[${expected}]`);
    if (r.error) console.log(`       ${r.error}`);
  }
}

console.log("=== A. 出力の関数形式（公式）===");
check("表示する(文字列)", [B('表示する("こんにちは")')], {}, "こんにちは");
check("表示する(変数)", [B("表示する(x)")], { x: 5 }, "5");
// 公式の例「表示する("平均点は", heikin)」は連結して表示される
check("表示する(複数引数)", [B('表示する("計は", x)')], { x: 5 }, "計は5");
check("表示する(式)", [B("表示する(x + 1)")], { x: 5 }, "6");
check("表示する(配列)", [B("表示する(A)")], { A: [1, 2] }, "[1, 2]");

console.log("\n=== B. 論理演算子（公式）===");
check("and", [B("もし x > 0 and x < 10 ならば:"), B('表示する("yes")', 1)], { x: 5 }, "yes");
check("or", [B("もし x < 0 or x > 3 ならば:"), B('表示する("yes")', 1)], { x: 5 }, "yes");
check("not", [B("もし not (x > 10) ならば:"), B('表示する("yes")', 1)], { x: 5 }, "yes");
check("and と or の混在", [B("もし x > 0 and (x < 3 or x > 4) ならば:"), B('表示する("yes")', 1)], { x: 5 }, "yes");

console.log("\n=== C. 整数除算と剰余（公式）===");
check("÷（整数除算）", [B("y = 7 ÷ 2"), B("表示する(y)")], {}, "3");
check("÷ を含む式", [B("y = (10 + 4) ÷ 3"), B("表示する(y)")], {}, "4");
check("%（剰余）", [B("y = 7 % 3"), B("表示する(y)")], {}, "1");
check("÷ と % の併用", [B("表示する(7 ÷ 2, 7 % 2)")], {}, "31");

console.log("\n=== D. 2次元配列（公式のカンマ添字）===");
// **現状は A[1,2] がエラーにならず undefined を返す（黙って誤答）。ここが一番危ない**
check("A[i,j] の参照", [B("表示する(A[1,2])")], { A: [[1, 2, 3], [4, 5, 6]] }, "6");
check("A[i,j] への代入", [B("A[0,1] = 99"), B("表示する(A[0,1])")], { A: [[1, 2], [3, 4]] }, "99");
check("A[i,j] を式の中で使う", [B("表示する(A[0,0] + A[1,1])")], { A: [[1, 2], [3, 4]] }, "5");

console.log("\n=== E. else if の語形（公式は「そうでなくもし」）===");
check(
  "そうでなくもし",
  [
    B("もし x > 10 ならば:"),
    B('表示する("A")', 1),
    B("そうでなくもし x > 3 ならば:"),
    B('表示する("B")', 1),
    B("そうでなければ:"),
    B('表示する("C")', 1),
  ],
  { x: 5 },
  "B"
);

console.log("\n=== F. 既存の書き方が壊れていないこと（回帰）===");
check("「〜 を表示する」（後置形式）", [B("x を表示する")], { x: 5 }, "5");
check("「かつ」", [B("もし x > 0 かつ x < 10 ならば:"), B("x を表示する", 1)], { x: 5 }, "5");
check("「または」", [B("もし x < 0 または x > 3 ならば:"), B("x を表示する", 1)], { x: 5 }, "5");
check("「の整数部分」", [B("y = 7 / 2 の整数部分"), B("y を表示する")], {}, "3");
check("「そうではなくもし」（従来の語形）", [
  B("もし x > 10 ならば:"), B('"A" を表示する', 1),
  B("そうではなくもし x > 3 ならば:"), B('"B" を表示する', 1),
], { x: 5 }, "B");
check("A[i][j]（従来の2次元表記）", [B("A[1][2] を表示する")], { A: [[1, 2, 3], [4, 5, 6]] }, "6");
check("for ループ", [
  B("合計 = 0"),
  B("i を 1 から 5 まで 1 ずつ増やしながら繰り返す:"),
  B("合計 = 合計 + i", 1),
  B("合計 を表示する"),
], {}, "15");
check("while ループと break", [
  B("i = 1"),
  B("i <= 10 の間、繰り返す:"),
  B("もし i == 3 ならば:", 1),
  B("ループを抜ける", 2),
  B("i = i + 1", 1),
  B("i を表示する"),
], {}, "3");
check("関数の定義と呼び出し", [
  B("関数 2倍にする(x) を定義する:"),
  B("返す x * 2", 1),
  B("2倍にする(5) を表示する"),
], {}, "10");

console.log("\n=== H. 文字列リテラルを壊さないこと（2026-07-30 第2ラウンド）===");
// 表記変換（and/or/not → && || !）が**文字列の中身まで置換してしまう**不具合。
// 探索アルゴリズムで "Not found" を表示するのは定番なので実害が出る。
// 対策: 変換の前に文字列リテラルを退避し、変換後に戻す（プレースホルダ方式）
check("英単語 not を含む文字列", [B('表示する("Not found")')], {}, "Not found");
check("英単語 and を含む文字列", [B('表示する("A and B")')], {}, "A and B");
check("英単語 or を含む文字列", [B('表示する("or")')], {}, "or");
check("単一引用符の文字列", [B("表示する('and')")], {}, "and");

console.log("\n=== I. 記号変換の取りこぼし（2026-07-30 第2ラウンド）===");
// 入れ子の添字。**エラーにならず誤った値を返す**ため、黙って誤答する点が危険
check("入れ子の添字 A[B[0],1]", [B("表示する(A[B[0],1])")], { A: [[1, 2], [3, 4]], B: [1] }, "4");
// ÷ の連続。a ÷ b ÷ c は普通に書きうる
check("÷ の連続", [B("表示する(100 ÷ 5 ÷ 2)")], {}, "10");
check("÷ の入れ子括弧", [B("表示する(((1 + 5)) ÷ 2)")], {}, "3");
check("÷ と括弧の組み合わせ", [B("表示する((8 + 4) ÷ (1 + 2))")], {}, "4");
// 負の数の整数除算は**床（floor）**で統一する（2026-07-30 判断）。
// オペランドの切り出しを正しく直せば Math.floor(-7 / 2) = -4 になり、
// 既存の「の整数部分」（Math.floor）とも一貫する
check("負の数の整数除算は床", [B("表示する(-7 ÷ 2)")], {}, "-4");
check("負の数の「の整数部分」も床", [B("表示する(-7 / 2 の整数部分)")], {}, "-4");

console.log("\n=== G. エラーメッセージが日本語になること ===");
{
  // 全角記号などを書いたとき、英語のまま出さない（現状 "Invalid or unexpected token" が素通り）
  const r = new DNCLInterpreter().run([B("y = 3 × 4")], {});
  const jaOk = !r.success && r.error && !/unexpected token/i.test(r.error) && !/Invalid/i.test(r.error);
  if (jaOk) { pass++; console.log("OK   記号エラーが日本語で説明される"); }
  else { fail++; console.log(`NG   記号エラーが日本語で説明される\n       ${r.error}`); }
}

console.log("\n==============================");
console.log(`成功: ${pass} 件 / 失敗: ${fail} 件`);
console.log("==============================");
if (fail > 0) process.exitCode = 1;
